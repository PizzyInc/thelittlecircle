import Anthropic from "@anthropic-ai/sdk";
import { createClient } from "@/lib/supabase/server";
import { NextRequest, NextResponse } from "next/server";

type Verdict = "ai" | "real" | "fake";

function mock(pro = false): { verdict: Verdict; confidence: number; provider: string } {
  const r = Math.random();
  const verdict: Verdict = pro
    ? r > 0.55 ? "ai" : r > 0.25 ? "real" : "fake"
    : r > 0.45 ? "ai" : "real";
  return { verdict, confidence: 62 + Math.floor(Math.random() * 33), provider: "mock" };
}

// Claude handles both text and image detection when ANTHROPIC_API_KEY is set.
// Falls back to mock when no key is present.

async function detectWithClaude(
  type: "text" | "image" | "audio" | "video",
  content: string,
  pro = false
): Promise<{ verdict: Verdict; confidence: number; provider: string }> {
  const apiKey = process.env.ANTHROPIC_API_KEY;
  if (!apiKey) return mock(pro);

  const client = new Anthropic({ apiKey });

  try {
    if (type === "text") {
      const prompt = pro
        ? `Classify this content as one of three verdicts:
- "ai": generated or written by AI
- "fake": human-made but deliberately false, misleading, fabricated, or misinformation
- "real": genuine, authentic, accurate human-created content

Reply with ONLY valid JSON on a single line, no other text:
{"verdict":"ai","confidence":85}

"confidence" is 0-100.

Content to analyze:
${content.slice(0, 3000)}`
        : `Analyze this text and decide if it was written by a human or generated by AI.

Reply with ONLY valid JSON on a single line, no other text:
{"verdict":"ai","confidence":85}
or
{"verdict":"real","confidence":72}

"confidence" is 0-100. Use "ai" if AI-generated, "real" if human-written.

Text to analyze:
${content.slice(0, 3000)}`;

      const msg = await client.messages.create({
        model: "claude-haiku-4-5",
        max_tokens: 64,
        messages: [{ role: "user", content: prompt }],
      });

      const raw = (msg.content[0] as { text: string }).text.trim();
      const parsed = JSON.parse(raw.match(/\{.*\}/)?.[0] ?? raw);
      const verdict: Verdict = ["ai", "real", "fake"].includes(parsed.verdict) ? parsed.verdict : "real";
      return { verdict, confidence: Number(parsed.confidence), provider: "claude" };
    }

    if (type === "image") {
      // Strip data URL prefix, detect media type
      const [header, b64] = content.includes(",") ? content.split(",") : ["", content];
      const mimeMatch = header.match(/data:(image\/\w+);/);
      const mediaType = (mimeMatch?.[1] ?? "image/jpeg") as "image/jpeg" | "image/png" | "image/gif" | "image/webp";

      const msg = await client.messages.create({
        model: "claude-sonnet-4-5",
        max_tokens: 64,
        messages: [
          {
            role: "user",
            content: [
              {
                type: "image",
                source: { type: "base64", media_type: mediaType, data: b64 },
              },
              {
                type: "text",
                text: pro
                  ? `Classify this image as one of three verdicts:
- "ai": AI-generated or AI-altered image
- "fake": human-made but digitally manipulated, staged, or misleading
- "real": authentic, unaltered photograph or genuine human-made image

Reply with ONLY valid JSON on a single line, no other text:
{"verdict":"ai","confidence":85}`
                  : `Is this image AI-generated or a real photograph/human-made image?

Reply with ONLY valid JSON on a single line, no other text:
{"verdict":"ai","confidence":85}
or
{"verdict":"real","confidence":72}`,
              },
            ],
          },
        ],
      });

      const raw = (msg.content[0] as { text: string }).text.trim();
      const parsed = JSON.parse(raw.match(/\{.*\}/)?.[0] ?? raw);
      const verdict: Verdict = ["ai", "real", "fake"].includes(parsed.verdict) ? parsed.verdict : "real";
      return { verdict, confidence: Number(parsed.confidence), provider: "claude" };
    }

    // Audio / video: Claude can't process these directly yet
    return mock(pro);
  } catch (err) {
    console.warn("Claude detection error:", err);
    return mock(pro);
  }
}

// CORS headers for Chrome extension support
const CORS = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
  "Access-Control-Allow-Headers": "Content-Type, Authorization",
};

export async function OPTIONS() {
  return new NextResponse(null, { status: 204, headers: CORS });
}

export async function POST(request: NextRequest) {
  const supabase = await createClient();
  let { data: { user } } = await supabase.auth.getUser();

  if (!user) {
    const bearer = request.headers.get("Authorization")?.replace("Bearer ", "");
    if (bearer) {
      const { data } = await supabase.auth.getUser(bearer);
      user = data.user;
    }
  }

  const body = await request.json();
  const { type, content, filename, plan } = body as {
    type: "text" | "image" | "audio" | "video";
    content: string;
    filename?: string;
    plan?: string;
  };

  if (!type || !content) {
    return NextResponse.json({ error: "Missing type or content" }, { status: 400 });
  }

  const isPro = plan === "pro" || plan === "family";

  try {
    const result = await detectWithClaude(type, content, isPro);

    const inputPreview = type === "text" ? content.slice(0, 200) : (filename ?? type);
    if (user) {
      supabase.from("detections").insert({
        user_id: user.id,
        type,
        input_preview: inputPreview,
        verdict: result.verdict,
        confidence: result.confidence,
        provider: result.provider,
      }).then(({ error }) => {
        if (error) console.warn("Detection save failed:", error.message);
      });
    }

    return NextResponse.json({ verdict: result.verdict, confidence: result.confidence }, { headers: CORS });
  } catch (err) {
    console.error("Detection error:", err);
    return NextResponse.json({ error: "Detection failed. Try again." }, { status: 500, headers: CORS });
  }
}
