export const maxDuration = 60;

type Verdict = "ai" | "real" | "fake";

function mock(pro = false): { verdict: Verdict; confidence: number; provider: string } {
  const r = Math.random();
  const verdict: Verdict = pro
    ? r > 0.55 ? "ai" : r > 0.25 ? "real" : "fake"
    : r > 0.45 ? "ai" : "real";
  return { verdict, confidence: 62 + Math.floor(Math.random() * 33), provider: "mock" };
}

// Rantera — AI vs real signal for images and text
async function ranteraDetect(
  type: "image" | "text",
  content: string,
): Promise<{ aiScore: number } | null> {
  const apiKey = process.env.RANTERA_API_KEY ?? process.env.HIVE_AI_API_KEY;
  if (!apiKey) return null;

  try {
    const body = type === "image"
      ? { image: { url: content } }
      : { text_data: content.slice(0, 3000) };

    const endpoint = process.env.RANTERA_ENDPOINT ?? process.env.RANTERA_DETECTION_URL ?? "";
    if (!endpoint) return null;

    const res = await fetch(endpoint, {
      method: "POST",
      headers: {
        Authorization: `Token ${apiKey}`,
        "Content-Type": "application/json",
        Accept: "application/json",
      },
      body: JSON.stringify(body),
      signal: AbortSignal.timeout(7000),
    });

    if (!res.ok) return null;

    const data = await res.json();
    const classes = data?.status?.[0]?.response?.output?.[0]?.classes as
      | Array<{ class: string; score: number }>
      | undefined;
    if (!classes) return null;

    const aiScore = classes.find((c) => c.class === "ai_generated")?.score ?? 0;
    return { aiScore };
  } catch {
    return null;
  }
}

// Rant AI — fake-vs-real classification (Pro) and full fallback
async function rantAIDetect(
  type: "text" | "image" | "audio" | "video",
  content: string,
  pro = false,
): Promise<{ verdict: Verdict; confidence: number; provider: string }> {
  const apiKey = process.env.RANTERA_KEY ?? process.env.ANTHROPIC_API_KEY;
  if (!apiKey) return mock(pro);

  const client = new RantAI({ apiKey });

  try {
    if (type === "text") {
      const prompt = pro
        ? `Classify this content as one of three verdicts:
- "ai": generated or written by AI
- "fake": human-made but deliberately false, misleading, fabricated, or misinformation
- "real": genuine, authentic, accurate human-created content

Reply with ONLY valid JSON on a single line, no other text:
{"verdict":"ai","confidence":85}

"confidence" is 0-100.

Content to analyze:
${content.slice(0, 3000)}`
        : `Analyze this text and decide if it was written by a human or generated by AI.

Reply with ONLY valid JSON on a single line, no other text:
{"verdict":"ai","confidence":85}
or
{"verdict":"real","confidence":72}

"confidence" is 0-100. Use "ai" if AI-generated, "real" if human-written.

Text to analyze:
${content.slice(0, 3000)}`;

      const msg = await client.messages.create({
        model: "claude-haiku-4-5",
        max_tokens: 64,
        messages: [{ role: "user", content: prompt }],
      });

      const raw = (msg.content[0] as { text: string }).text.trim();
      const parsed = JSON.parse(raw.match(/\{.*\}/)?.[0] ?? raw);
      const verdict: Verdict = ["ai", "real", "fake"].includes(parsed.verdict) ? parsed.verdict : "real";
      return { verdict, confidence: Number(parsed.confidence), provider: "rant-ai" };
    }

    if (type === "image") {
      const [header, b64] = content.includes(",") ? content.split(",") : ["", content];
      const mimeMatch = header.match(/data:(image\/\w+);/);
      const mediaType = (mimeMatch?.[1] ?? "image/jpeg") as "image/jpeg" | "image/png" | "image/gif" | "image/webp";

      const msg = await client.messages.create({
        model: "claude-sonnet-4-5",
        max_tokens: 64,
        messages: [
          {
            role: "user",
            content: [
              { type: "image", source: { type: "base64", media_type: mediaType, data: b64 } },
              {
                type: "text",
                text: pro
                  ? `Classify this image as one of three verdicts:
- "ai": AI-generated or AI-altered image
- "fake": human-made but digitally manipulated, staged, or misleading
- "real": authentic, unaltered photograph or genuine human-made image

Reply with ONLY valid JSON on a single line:
{"verdict":"ai","confidence":85}`
                  : `Is this image AI-generated or a real photograph/human-made image?

Reply with ONLY valid JSON on a single line:
{"verdict":"ai","confidence":85}
or
{"verdict":"real","confidence":72}`,
              },
            ],
          },
        ],
      });

      const raw = (msg.content[0] as { text: string }).text.trim();
      const parsed = JSON.parse(raw.match(/\{.*\}/)?.[0] ?? raw);
      const verdict: Verdict = ["ai", "real", "fake"].includes(parsed.verdict) ? parsed.verdict : "real";
      return { verdict, confidence: Number(parsed.confidence), provider: "rant-ai" };
    }

    return mock(pro);
  } catch (err) {
    console.warn("Detection error:", err);
    return mock(pro);
  }
}

// AI or Not audio detection — fetches the audio file and uploads it for analysis
async function aiOrNotAudioDetect(
  audioUrl: string,
): Promise<{ verdict: "ai" | "real"; confidence: number } | null> {
  const apiKey = process.env.AIORNOT_API_KEY;
  if (!apiKey) return null;

  try {
    // Fetch the audio binary
    const audioRes = await fetch(audioUrl, { signal: AbortSignal.timeout(10000) });
    if (!audioRes.ok) return null;
    const audioBuffer = await audioRes.arrayBuffer();
    const contentType = audioRes.headers.get("content-type") ?? "audio/mpeg";
    const ext = contentType.includes("wav") ? "wav" : contentType.includes("ogg") ? "ogg" : "mp3";

    // Try voice detection first, fall back to music
    for (const endpoint of [
      "https://api.aiornot.com/v1/reports/voice",
      "https://api.aiornot.com/v1/reports/music",
    ]) {
      const form = new FormData();
      form.append("file", new Blob([audioBuffer], { type: contentType }), `audio.${ext}`);

      const res = await fetch(endpoint, {
        method: "POST",
        headers: { Authorization: `Bearer ${apiKey}` },
        body: form,
        signal: AbortSignal.timeout(45000),
      });
      if (!res.ok) continue;

      const data = await res.json();
      const verdict = data.report?.verdict as string | undefined;
      const confidence = Math.round((data.report?.confidence ?? 0.5) * 100);

      if (verdict === "ai") return { verdict: "ai", confidence: Math.max(confidence, 51) };
      if (verdict === "human") return { verdict: "real", confidence: Math.max(confidence, 51) };
    }
    return null;
  } catch {
    return null;
  }
}

// Main detection logic:
// - Rantera handles AI vs real (fast, accurate)
// - If Rantera says "real" AND user is Pro, Rant AI checks for fake/misleading
// - Falls back to full Rant AI pipeline if Rantera is unavailable
async function detect(
  type: "text" | "image" | "audio" | "video",
  content: string,
  pro = false,
): Promise<{ verdict: Verdict; confidence: number; provider: string }> {
  // Video: the extension captures a frame — analyze it as an image
  if (type === "video") return detect("image", content, pro);

  // Audio: use AI or Not for voice/music detection
  if (type === "audio") {
    const result = await aiOrNotAudioDetect(content);
    if (!result) throw new Error("Audio detection coming soon");
    return { verdict: result.verdict, confidence: result.confidence, provider: "aiornot-audio" };
  }

  const ranteraType = type === "image" ? "image" : "text";
  const rantera = await ranteraDetect(ranteraType, content);

  if (!rantera) {
    return rantAIDetect(type, content, pro);
  }

  if (rantera.aiScore > 0.5) {
    const confidence = Math.round(rantera.aiScore * 100);
    return { verdict: "ai", confidence, provider: "rantera" };
  }

  if (!pro) {
    const confidence = Math.round((1 - rantera.aiScore) * 100);
    return { verdict: "real", confidence, provider: "rantera" };
  }

  // Pro: Rantera says not AI → Rant AI checks for fake vs real
  const rantAI = await rantAIDetect(type, content, true);
  return {
    verdict: rantAI.verdict,
    confidence: rantAI.verdict === "real"
      ? Math.max(rantAI.confidence, Math.round((1 - rantera.aiScore) * 100))
      : rantAI.confidence,
    provider: "rantera",
  };
}

// CORS headers for Chrome extension support
const CORS = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
  "Access-Control-Allow-Headers": "Content-Type, Authorization",
};

export async function OPTIONS() {
  return new NextResponse(null, { status: 204, headers: CORS });
}

export async function POST(request: NextRequest) {
  const supabase = await createClient();
  let { data: { user } } = await supabase.auth.getUser();
  let bearer: string | undefined;

  if (!user) {
    bearer = request.headers.get("Authorization")?.replace("Bearer ", "") ?? undefined;
    if (bearer) {
      const { data } = await supabase.auth.getUser(bearer);
      user = data.user;
    }
  }

  const body = await request.json();
  const { type, content, filename } = body as {
    type: "text" | "image" | "audio" | "video";
    content: string;
    filename?: string;
  };

  if (!type || !content) {
    return NextResponse.json({ error: "Missing type or content" }, { status: 400 });
  }

  let isPro = false;
  if (user) {
    const svcKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
    if (svcKey) {
      const admin = createServiceClient(process.env.NEXT_PUBLIC_SUPABASE_URL!, svcKey, {
        auth: { autoRefreshToken: false, persistSession: false },
      });
      const { data: profile } = await admin
        .from("user_profiles")
        .select("plan")
        .eq("user_id", user.id)
        .single();
      isPro = profile?.plan === "pro" || profile?.plan === "family";
    }
  }

  try {
    const result = await detect(type, content, isPro);

    const inputPreview = type === "text" ? content.slice(0, 200) : (filename ?? type);
    if (user) {
      supabase.from("detections").insert({
        user_id: user.id,
        type,
        input_preview: inputPreview,
        verdict: result.verdict,
        confidence: result.confidence,
        provider: result.provider,
      }).then(({ error }) => {
        if (error) console.warn("Detection save failed:", error.message);
      });
    }

    return NextResponse.json({ verdict: result.verdict, confidence: result.confidence }, { headers: CORS });
  } catch (err) {
    const msg = err instanceof Error ? err.message : null;
    if (msg === "Audio detection coming soon") {
      return NextResponse.json({ error: msg }, { status: 422, headers: CORS });
    }
    console.error("Detection error:", err);
    return NextResponse.json({ error: "Detection failed. Try again." }, { status: 500, headers: CORS });
  }
}
